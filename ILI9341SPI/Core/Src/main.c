void DibujarFondoEstrellas(void)
{
	LCD_Clear(COLOR_FONDO);

	for (uint32_t i = 0; i < CANTIDAD_ESTRELLAS; i++)
	{
		FillRect(estrellas[i].x,
				 estrellas[i].y,
				 estrellas[i].tamano,
				 estrellas[i].tamano,
				 estrellas[i].color);
	}
}

void ActualizarEstrellas(void)
{
	uint32_t ahora = HAL_GetTick();

	if ((ahora - tiempoEstrellasAnterior) < ESTRELLAS_DELAY_MS)
	{
		return;
	}

	tiempoEstrellasAnterior = ahora;

	for (uint32_t i = 0; i < CANTIDAD_ESTRELLAS; i++)
	{
		// Borra la posicion anterior de la estrella
		FillRect(estrellas[i].x,
				 estrellas[i].y,
				 estrellas[i].tamano,
				 estrellas[i].tamano,
				 COLOR_FONDO);

		// Movimiento hacia la izquierda
		if (estrellas[i].x <= estrellas[i].velocidad)
		{
			estrellas[i].x = SCREEN_WIDTH - estrellas[i].tamano;
		}
		else
		{
			estrellas[i].x -= estrellas[i].velocidad;
		}

		// Dibuja la estrella en su nueva posicion
		FillRect(estrellas[i].x,
				 estrellas[i].y,
				 estrellas[i].tamano,
				 estrellas[i].tamano,
				 estrellas[i].color);
	}
}

void RestaurarFondoEstrellas(int x,
							 int y,
							 int ancho,
							 int alto)
{
	FillRect(x, y, ancho, alto, COLOR_FONDO);

	for (uint32_t i = 0; i < CANTIDAD_ESTRELLAS; i++)
	{
		int estrellaX = estrellas[i].x;
		int estrellaY = estrellas[i].y;
		int estrellaTamano = estrellas[i].tamano;

		if ((estrellaX < x + ancho) &&
			(estrellaX + estrellaTamano > x) &&
			(estrellaY < y + alto) &&
			(estrellaY + estrellaTamano > y))
		{
			FillRect(estrellas[i].x,
					 estrellas[i].y,
					 estrellas[i].tamano,
					 estrellas[i].tamano,
					 estrellas[i].color);
		}
	}
}

void ConvertirSpriteRGB565(const uint8_t *bytes,
						   uint16_t *sprite,
						   int cantidadPixeles)
{
	for (int i = 0; i < cantidadPixeles; i++)
	{
		sprite[i] = ((uint16_t)bytes[i * 2] << 8) |
					bytes[i * 2 + 1];
	}
}

void RotarSprite90Horario(const uint16_t *original,
						  uint16_t *rotado,
						  int ancho,
						  int alto)
{
	for (int y = 0; y < alto; y++)
	{
		for (int x = 0; x < ancho; x++)
		{
			rotado[x * alto + (alto - 1 - y)] =
					original[y * ancho + x];
		}
	}
}

void Disparar(void)
{
	if (!balaActiva)
	{
		balaX = naveX + SPRITE_SIZE;
		balaY = naveY;
		balaActiva = 1;
	}
}

int ColisionBalaEnemigo(void)
{
	if (!balaActiva || !enemigoVivo)
	{
		return 0;
	}

	if ((balaX < enemigoX + SPRITE_SIZE) &&
		(balaX + SPRITE_SIZE > enemigoX) &&
		(balaY < enemigoY + SPRITE_SIZE) &&
		(balaY + SPRITE_SIZE > enemigoY))
	{
		return 1;
	}

	return 0;
}

